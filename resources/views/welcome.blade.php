        function selectSituation(type) {
            const formSection = document.getElementById('assessment');
            formSection.scrollIntoView({ behavior: 'smooth' });

            // Uncheck all services first
            ['srv-legalization', 'srv-work-permit', 'srv-trc', 'srv-visa', 'srv-police-check', 'srv-not-sure'].forEach(id => {
                const el = document.getElementById(id);
                if (el) el.checked = false;
            });

            if (type === 'moving-to-vietnam') {
                document.getElementById('srv-legalization').checked = true;
                const locRadio = document.querySelector('input[name="location"][value="outside-vietnam"]');
                if (locRadio) locRadio.checked = true;
            } else if (type === 'job-offer') {
                document.getElementById('srv-work-permit').checked = true;
                document.getElementById('srv-legalization').checked = true;
            } else if (type === 'changing-schools') {
                document.getElementById('srv-trc').checked = true;
                document.getElementById('srv-work-permit').checked = true;
            } else if (type === 'expiring-soon') {
                document.getElementById('srv-visa').checked = true;
                const urgentRadio = document.querySelector('input[name="urgency"][value="urgent"]');
                if (urgentRadio) urgentRadio.checked = true;
            }
        }

        function preselectService(serviceCode) {
            const formSection = document.getElementById('assessment');
            formSection.scrollIntoView({ behavior: 'smooth' });

            const targetId = 'srv-' + serviceCode;
            const el = document.getElementById(targetId);
            if (el) el.checked = true;
        }

        function handleAssessmentSubmit(event) {
            event.preventDefault();
            document.getElementById('assessmentForm').classList.add('hidden');
            document.getElementById('formSuccessMessage').classList.remove('hidden');
        }
